export async function syncCatalog() {
  console.log(`Iniciando sincronización de catálogo (${CATALOG_PRODUCTS.length} referencias)...`);
  let created = 0;
  let updated = 0;

  for (const prod of CATALOG_PRODUCTS) {
    const data = {
      reference: prod.reference,
      name: prod.name,
      line: prod.line as ProductLine,
      category: prod.category as ProductCategory,
      priceList: prod.priceList,
      priceDistributor: prod.priceDistributor,
      cost: prod.cost,
      stock: prod.stock,
      minStock: prod.minStock,
      unit: prod.unit,
      isKit: prod.isKit ?? false,
      active: true,
    };

    const result = await prisma.product.upsert({
      where: { reference: prod.reference },
      create: data,
      update: {
        name: data.name,
        line: data.line,
        category: data.category,
        priceList: data.priceList,
        priceDistributor: data.priceDistributor,
        cost: data.cost,
        isKit: data.isKit,
        active: true,
      },
    });
    
    if (result.createdAt.getTime() === result.updatedAt.getTime()) {
      created++;
    } else {
      updated++;
    }
  }

  console.log(`Catálogo sincronizado exitosamente: ${created} creados, ${updated} actualizados. Total: ${CATALOG_PRODUCTS.length}`);
}

if (require.main === module) {
  syncCatalog()
    .catch((e) => {
      console.error('Error al sincronizar catálogo:', e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
